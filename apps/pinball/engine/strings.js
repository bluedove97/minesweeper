export function get_rc_string(id) {
  return rc_strings[id] ?? '';
}

// snprintf with %d / %ld / %s, truncated like a char[bufferSize] buffer.
export function sprintf(bufferSize, format, ...args) {
  let i = 0;
  const out = format.replace(/%l?[ds]/g, spec => {
    const arg = args[i++];
    return spec.endsWith('s') ? String(arg) : String(Math.trunc(arg) | 0);
  });
  return out.slice(0, bufferSize - 1);
}
